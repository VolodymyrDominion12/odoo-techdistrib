# -*- coding: utf-8 -*-
# =============================================================================
#  Модель: techdistrib.dealer.tier — довідник рівнів дилерського партнерства
# =============================================================================
#  Це НОВА модель (не розширення існуючої). Таблиця в Postgres буде створена
#  автоматично і називатиметься techdistrib_dealer_tier — ORM перетворює
#  крапки на підкреслення.
#
#  НАВІЩО ЦЕЙ ДОВІДНИК, А НЕ ПРОСТИЙ СПИСОК (Selection)?
#  Наївне рішення — зробити поле-вибір:
#      dealer_tier = fields.Selection([('bronze','Bronze'), ...])
#  Це погано, бо:
#    1. додати новий рівень = змінити код і перезапустити сервер;
#    2. неможливо зберігати параметри рівня (мінімальний оборот, знижки);
#    3. неможливо зробити зв'язок «усі дилери цього рівня» одним запитом.
#  Окрема модель дає все це безкоштовно.
#
#  Це класичний приклад правила: «якщо в сутності є атрибути — роби модель».
# =============================================================================

from odoo import api, fields, models, _


class TechdistribDealerTier(models.Model):
    # _name — технічна назва моделі. Це НАЗАВЖДИ: вона стає іменем таблиці
    # і частиною XML ID. Перейменувати модель у продакшені дуже боляче.
    # Конвенція: <назва_модуля_скорочено>.<сутність>
    _name = 'techdistrib.dealer.tier'

    # _description — обов'язковий для нових моделей. Показується в
    # Technical → Models і використовується в логах.
    _description = 'Рівень дилерського партнерства'

    # _order — типовий ORDER BY для search() без явного order.
    # 'sequence desc' означає: Platinum (50) буде вище за Bronze (10).
    # Зверни увагу на синтаксис 'field desc' — саме так, як в SQL.
    _order = 'sequence desc, name'

    # --- Поля -----------------------------------------------------------------

    name = fields.Char(
        string='Назва',
        required=True,
        # translate=True означає, що значення можна перекласти на інші мови.
        # Для довідників це майже завжди правильне рішення.
        translate=True,
    )

    code = fields.Char(
        string='Код',
        required=True,
        help='Технічний код рівня. Використовується в коді й імпорті, '
             'тому краще латиницею: bronze, silver, gold, platinum.',
    )

    sequence = fields.Integer(
        string='Порядок',
        default=10,
        help='Чим більше число — тим ВИЩИЙ рівень партнера. '
             'Використовується для сортування та для зниження рівня на один щабель.',
    )

    # --- Гроші -----------------------------------------------------------------
    # Monetary — це Float, який «знає» свою валюту. Він зберігає лише число,
    # а валюту бере з окремого поля, вказаного в currency_field.
    #
    # ЧОМУ НЕ ПРОСТО FLOAT: Monetary автоматично форматує суму за правилами
    # валюти (розділювачі, кількість знаків) і правильно поводиться при
    # мультивалютності. Для грошових сум у Odoo завжди використовуй Monetary.
    currency_id = fields.Many2one(
        comodel_name='res.currency',
        string='Валюта',
        # default як lambda: обчислюється В МОМЕНТ створення запису, коли
        # env уже доступне. Якщо написати просто self.env.company... —
        # буде помилка, бо self ще не існує на етапі оголошення класу.
        default=lambda self: self.env.company.currency_id.id,
        required=True,
    )

    min_annual_revenue = fields.Monetary(
        string='Мінімальний річний оборот',
        currency_field='currency_id',
        help='Поріг обороту, з якого дилер може претендувати на цей рівень. '
             'Використовується як орієнтир для менеджера, автоматично рівень не змінює.',
    )

    # --- Пов'язані дані --------------------------------------------------------
    # One2many — «зворотний бік» Many2one.
    # Ключове: One2many НЕ СТВОРЮЄ колонку в таблиці рівня!
    # Це просто зручний спосіб подивитись на вже наявний зв'язок:
    # він читає поле dealer_tier_id з таблиці res_partner.
    #
    # Другий аргумент ('dealer_tier_id') — ЦЕ ОБОВ'ЯЗКОВО назва поля
    # Many2one на ІНШІЙ моделі. Помилка тут = помилка при завантаженні модуля.
    partner_ids = fields.One2many(
        comodel_name='res.partner',
        inverse_name='dealer_tier_id',
        string='Дилери цього рівня',
    )

    partner_count = fields.Integer(
        string='Кількість дилерів',
        compute='_compute_partner_count',
    )

    active = fields.Boolean(
        string='Активний',
        default=True,
        help='Знятий прапорець приховує запис з усіх списків, '
             'але не видаляє його. Так Odoo реалізує «мʼяке видалення».',
    )

    description = fields.Text(
        string='Умови рівня',
        help='Опис умов партнерської програми для цього рівня.',
    )

    # --- SQL-обмеження ---------------------------------------------------------
    # Це обмеження рівня БАЗИ ДАНИХ, а не Python.
    # Формат: (ім'я_обмеження, SQL_вираз, повідомлення_про_помилку).
    #
    # ЧОМУ ЦЕ КРАЩЕ ЗА @api.constrains:
    #   * перевіряється навіть при прямому імпорті даних і при конкурентних
    #     транзакціях (два запити одночасно створять дубль — Python-перевірка
    #     цього не зловить, а UNIQUE в базі зловить);
    #   * швидше, бо індекс будується базою.
    #
    # Повідомлення обов'язково брати в _() — інакше воно не перекладатиметься.
    _sql_constraints = [
        ('code_uniq', 'unique(code)', 'Код рівня має бути унікальним!'),
        ('name_uniq', 'unique(name)', 'Рівень з такою назвою вже існує!'),
    ]

    # --- Обчислювані поля ------------------------------------------------------

    # Декоратор @api.depends каже ORM: «коли зміниться partner_ids —
    # перерахуй це поле». Без нього поле ніколи не оновиться.
    #
    # Метод-обчислювач ЗОБОВ'ЯЗАНИЙ присвоїти значення КОЖНОМУ запису
    # в self. Забудеш хоч один — Odoo видасть помилку
    # "Compute method failed to assign ...".
    @api.depends('partner_ids')
    def _compute_partner_count(self):
        for tier in self:
            tier.partner_count = len(tier.partner_ids)

    # --- Методи ----------------------------------------------------------------

    # Метод, який викликається кнопкою з UI.
    # Конвенція Odoo: методи, що викликаються з інтерфейсу, називаються
    # action_* і ПОВЕРТАЮТЬ словник-дію (або False, якщо нічого не треба).
    def action_view_partners(self):
        # ensure_one() — захисний виклик: він падає з зрозумілою помилкою,
        # якщо метод викликали на наборі з кількох записів.
        # Став його всюди, де логіка має сенс лише для ОДНОГО запису.
        self.ensure_one()
        return {
            'type': 'ir.actions.act_window',
            'name': _('Дилери рівня %s', self.name),
            'res_model': 'res.partner',
            'view_mode': 'list,form',
            'domain': [('dealer_tier_id', '=', self.id)],
            'context': {'default_is_dealer': True, 'default_dealer_tier_id': self.id},
        }
