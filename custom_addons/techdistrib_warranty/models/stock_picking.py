# =============================================================================
#  Це найцікавіше місце модуля з погляду інтеграції: ми втручаємось
#  у СТАНДАРТНИЙ складський процес Odoo.
#
#  Коли комірник натискає «Підтвердити» на відвантаженні, Odoo:
#      * списує товар зі складу;
#      * створює бухгалтерські проводки (якщо ввімкнено);
#      * фіксує, які саме серійні номери пішли клієнту.
#
#  Ми додаємо до цього ще один крок: проставляємо гарантійні дати
#  на кожен серійний номер.
# =============================================================================

import logging

from odoo import fields, models

_logger = logging.getLogger(__name__)


class StockPicking(models.Model):
    _inherit = 'stock.picking'

    def _action_done(self):
        """Точка перехоплення: після завершення переміщення.

        ⚠️ ЧОМУ _action_done, А НЕ button_validate.

        У stock.picking є два схожі методи:

            button_validate()  — те, що натискає КОРИСТУВАЧ у формі.
                                 Робить перевірки, питає про backorder,
                                 показує візарди «що робити з рештою».
            _action_done()     — те, що РЕАЛЬНО виконує переміщення.
                                 Викликається з button_validate, але
                                 також напряму з коду, з імпорту,
                                 з інших модулів, із cron.

        Якби ми перевизначили button_validate, гарантія проставлялась би
        лише тоді, коли комірник натиснув кнопку. А якщо відвантаження
        завершив інший модуль або імпорт — гарантії не було б.

        ПРАВИЛО (те саме, що в Модулі 2 з action_confirm):
        перехоплюй НАЙГЛИБШИЙ метод, який виконує дію, а не той,
        який натискає користувач.
        """
        result = super()._action_done()

        # ⚠️ ВАЖЛИВО: super() викликано ПЕРШИМ, і це правильно.
        #
        # У Модулі 2 (кредитний ліміт) ми робили навпаки — перевіряли ДО
        # super(), бо там ішлося про ЗАБОРОНУ дії: якщо умову не виконано,
        # дію виконувати не можна.
        #
        # Тут мета протилежна: ми не забороняємо, а ДОПОВНЮЄМО вже
        # виконану дію. Гарантію можна проставити лише тоді, коли
        # переміщення вже завершено (стан 'done', відомі серійні номери
        # й дата). Тому спершу super(), потім наша логіка.
        #
        # ПРАВИЛО: перевірки — ДО super(); доповнення результату — ПІСЛЯ.
        self._techdistrib_apply_warranty_dates()

        return result

    def _techdistrib_apply_warranty_dates(self):
        """Проставити гарантійні дати для серійних номерів у відвантаженні."""
        for picking in self:
            # 1. Обробляємо лише завершені переміщення.
            #    _action_done може викликатись і в процесі; беремо тільки 'done'.
            if picking.state != 'done':
                continue

            # 2. Обробляємо лише ВИХІДНІ переміщення (нам → клієнт).
            #    picking_type_code буває: 'incoming', 'outgoing', 'internal'.
            #    Для 'incoming' (від вендора) гарантія не починається —
            #    вона стартує при продажі, а не при закупівлі.
            if picking.picking_type_code != 'outgoing':
                continue

            # 3. Дата початку гарантії = дата відвантаження.
            #    date_done — момент завершення; беремо дату без часу.
            delivery_date = (picking.date_done or fields.Datetime.now()).date()

            # 4. sale_id з'являється на stock.picking завдяки модулю sale_stock.
            #    Може бути порожнім, якщо відвантаження створили вручну.
            sale_order = picking.sale_id

            applied = 0
            for move_line in picking.move_line_ids:
                lot = move_line.lot_id
                if not lot:
                    # Товар без обліку за серійним номером — гарантію
                    # вести нічим. Це нормально: у нас лише 35 % SKU
                    # обліковуються за номерами.
                    continue
                if lot._apply_warranty_dates(
                        picking.partner_id, sale_order, delivery_date):
                    applied += 1

            if applied:
                _logger.info(
                    'TechDistrib: гарантію проставлено для %s серійних '
                    'номерів у відвантаженні %s (дата %s).',
                    applied, picking.name, delivery_date,
                )

    def action_view_warranty_claims(self):
        """Кнопка «Гарантійні звернення» на відвантаженні.

        Корисний шлях: комірник бачить, що по цьому відвантаженні вже
        є звернення — перш ніж приймати повернення.
        """
        self.ensure_one()
        lots = self.move_line_ids.lot_id
        return {
            'type': 'ir.actions.act_window',
            'name': 'Гарантійні звернення',
            'res_model': 'techdistrib.warranty.claim',
            'view_mode': 'list,form',
            'domain': [('lot_id', 'in', lots.ids)],
        }
